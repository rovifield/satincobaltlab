#include <string>
#include <vector>

void balanced_sum() {
    int left = 1 + 2 + 3;
    int right = 4 + 2;
    bool balanced = (left == right);
    (void)balanced;
}

void count_multiples() {
    int count = 0;
    for (int i = 1; i <= 100; ++i) {
        if (i % 7 == 0) count += 1;
    }
    (void)count;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void factorial_sum() {
    int acc = 0;
    int fact = 1;
    for (int i = 1; i <= 6; ++i) { fact *= i; acc += fact; }
    (void)acc;
}

extern "C" int gentle_crescent();
extern "C" void frost_lantern();
extern "C" void verdant_signal();

int main() {
    balanced_sum();
    count_multiples();
    text_contains();
    factorial_sum();
    frost_lantern();
    verdant_signal();
    return gentle_crescent();
}
